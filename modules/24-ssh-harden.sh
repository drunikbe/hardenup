# shellcheck shell=bash
# =============================================================================
# 24-ssh-harden.sh — Harden sshd via drop-in config
# =============================================================================
#
# Writes /etc/ssh/sshd_config.d/99-hardening.conf. Validates with `sshd -t`
# before reloading the service — refuses to proceed if validation fails,
# rolling back the drop-in file so the previous (working) config stands.
#
# Pauses after reload so the operator can verify access from a second
# terminal; on "no", rolls back and exits. Load-bearing: removing this
# pause turns any sshd_config typo into a permanent lockout on a remote box.
# =============================================================================

MODULE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=/dev/null
source "${MODULE_DIR}/../lib.sh"
# shellcheck source=/dev/null
source "${MODULE_DIR}/../state.sh"

SSH_HARDENING_FILE="/etc/ssh/sshd_config.d/99-hardening.conf"

applies_ssh_harden() { return 0; }

detect_ssh_harden() {
    [[ -n "$(state_get SSH_PORT)" ]] && return 0
    # Try to read a previously-applied port from the drop-in file.
    if [[ -f "$SSH_HARDENING_FILE" ]]; then
        local p
        p="$(awk '/^Port /{print $2; exit}' "$SSH_HARDENING_FILE" 2>/dev/null)"
        [[ -n "$p" ]] && state_set SSH_PORT "$p"
    fi
    [[ -z "$(state_get SSH_PORT)" ]] && state_set SSH_PORT "22"
}

configure_ssh_harden() {
    info "Locks sshd to key-only auth, disables root login, rate-limits,"
    info "and pauses for you to verify access from a second terminal."
    if ! ask_yesno "Harden the SSH daemon?" "y"; then
        state_mark_skipped ssh_harden
        return 0
    fi
    while true; do
        ask_input "SSH port (non-standard reduces bot noise)" "$(state_get SSH_PORT 22)" '^[0-9]+$'
        if validate_port "$REPLY"; then
            state_set SSH_PORT "$REPLY"
            break
        fi
        err "Invalid port: $REPLY"
    done

    # Tailscale SSH sub-prompt: only meaningful when VPN_KIND=tailscale.
    # WireGuard has no equivalent — it's a protocol, not an SSH identity
    # system. Default 'n' — sshd-everywhere is the simpler trust model.
    # See module header for the "two SSH servers, one host" explanation.
    if [[ "$(state_get VPN_KIND)" == tailscale ]]; then
        info "Tailscale SSH is a SEPARATE SSH server inside tailscaled that handles"
        info "tailnet connections with SSO + ACL auth (no SSH keys). sshd is unchanged"
        info "and still handles every other path. Say 'n' if you want sshd responsible"
        info "for all SSH on this host (simpler mental model, keys required everywhere)."
        if ask_yesno "Enable Tailscale SSH for tailnet connections?" "n"; then
            state_set TAILSCALE_SSH yes
        else
            state_set TAILSCALE_SSH no
        fi
    else
        state_set TAILSCALE_SSH no
    fi
}

# Announced by `main.sh --dry-run` so a recipe run's pauses are visible in
# advance. run_ raises the pause only when a non-root user exists to test the
# new config with; at plan time USER_NAME may not have been answered yet, so
# announce whenever 21-user is also going to run — that's when one will.
critical_prompts_ssh_harden() {
    if [[ -n "$(state_get USER_NAME)" ]] || ! state_skipped user; then
        echo "confirm SSH still works from a second terminal (rolls back on 'no')"
    fi
    return 0
}

check_ssh_harden() {
    [[ -f "$SSH_HARDENING_FILE" ]] || return 1
    grep -q "^Port $(state_get SSH_PORT)\$" "$SSH_HARDENING_FILE"
}

run_ssh_harden() {
    detect_ssh_service || { err "Could not find SSH service"; exit 1; }

    local ssh_port user allow
    ssh_port="$(state_get SSH_PORT)"
    user="$(state_get USER_NAME)"
    allow=""
    [[ -n "$user" ]] && allow="AllowUsers ${user}"

    backup_file "$SSH_HARDENING_FILE"
    cat > "$SSH_HARDENING_FILE" <<EOF
# Generated by modules/24-ssh-harden.sh on $(date -u +"%Y-%m-%d %H:%M:%S UTC")
Port ${ssh_port}
PermitRootLogin no
PubkeyAuthentication yes
PasswordAuthentication no
PermitEmptyPasswords no
KbdInteractiveAuthentication no
X11Forwarding no
MaxAuthTries 3
MaxSessions 3
LoginGraceTime 30
ClientAliveInterval 300
ClientAliveCountMax 2
AllowTcpForwarding no
AllowAgentForwarding no
HostbasedAuthentication no
${allow}
Ciphers aes256-gcm@openssh.com,chacha20-poly1305@openssh.com,aes256-ctr
MACs hmac-sha2-512-etm@openssh.com,hmac-sha2-256-etm@openssh.com
KexAlgorithms curve25519-sha256,curve25519-sha256@libssh.org
EOF

    # Validate the full SSH configuration before reloading. If sshd -t fails
    # the daemon would refuse to restart, locking out the operator.
    local sshd_output
    if sshd_output=$(sshd -t 2>&1); then
        systemctl reload "$SSH_SERVICE"
        log "SSH hardened (key-only, no root, port ${ssh_port}) [service: ${SSH_SERVICE}]"
    else
        err "SSH config validation failed:"
        err "$sshd_output"
        rm -f "$SSH_HARDENING_FILE"
        exit 1
    fi

    # Safety net: operator must confirm access from another terminal.
    if [[ -n "$user" ]]; then
        echo ""
        warn "═══════════════════════════════════════════════════════════════"
        warn "  IMPORTANT: Do NOT close this terminal session!"
        warn "  Open a NEW terminal and verify SSH access:"
        warn "  ssh -p ${ssh_port} ${user}@<this-server-ip>"
        warn "═══════════════════════════════════════════════════════════════"
        echo ""
        if ! ask_confirm_critical "Have you verified SSH access in another terminal?" "n"; then
            warn "Rolling back SSH hardening..."
            rm -f "$SSH_HARDENING_FILE"
            systemctl reload "$SSH_SERVICE"
            err "SSH hardening rolled back. Re-run after verifying access."
            exit 1
        fi
    fi

    # Apply Tailscale SSH toggle last so sshd hardening is already in force
    # regardless of outcome. Idempotent: `tailscale set` is a no-op when the
    # requested state already matches. Only relevant when VPN_KIND=tailscale;
    # for WireGuard or none, there's no tailscaled to toggle.
    if [[ "$(state_get VPN_KIND)" == tailscale ]]; then
        if [[ "$(state_get TAILSCALE_SSH no)" == yes ]]; then
            tailscale set --ssh
            log "Tailscale SSH enabled (tailnet connections now handled by tailscaled)"
        else
            tailscale set --ssh=false
            log "Tailscale SSH disabled — sshd handles all SSH paths"
        fi
    fi
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    require_root
    state_init
    detect_ssh_harden
    configure_ssh_harden
    state_skipped ssh_harden && exit 0
    check_ssh_harden && { log "SSH already hardened with this port; skipping."; exit 0; }
    run_ssh_harden
    check_ssh_harden || { err "SSH harden verification failed"; exit 1; }
fi
